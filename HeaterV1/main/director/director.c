static void director_task(void *arg)
{
    director_args_full_t *a = (director_args_full_t*)arg;
    g_button_queue = a->button_q;
    g_jumbo_queue  = a->sample_q;
    g_initial_pd_caps = a->pd_caps;
    vPortFree(a); // release argument struct
    configASSERT(g_button_queue);
    // Initialize LVGL
    lv_init();

    // 1ms periodic esp_timer to advance LVGL tick (OK to call from timer)
    esp_timer_create_args_t periodic_timer_args = {
        .callback = &lv_tick_cb,
        .arg = NULL,
        .name = "lv_tick"
    };

    ESP_ERROR_CHECK(esp_timer_create(&periodic_timer_args, &lv_tick_timer));
    ESP_ERROR_CHECK(esp_timer_start_periodic(lv_tick_timer, 1000)); // 1000 us = 1 ms

    lvgl_init_display();

    ui_init(NULL);
    lv_obj_t * home_screen = home_create();
    lv_scr_load(home_screen);

    // Locate and cache the autogenerated container by its LVGL name
    s_page_container = find_obj_by_name(home_screen, "page_container");
    if (!s_page_container) {
        ESP_LOGW("director", "page_container not found (name may have changed in autogenerated code)");
    }

    // Create the LVGL clock timer (start paused; we control via button)
    ui_clock_timer = lv_timer_create(ui_clock_cb, 1000, NULL);
    lv_timer_pause(ui_clock_timer);
    // Create always-on blink timer for Settings selection (faster blink)
    settings_blink_timer = lv_timer_create(settings_blink_cb, 500, NULL);
    // Initialize last input time and create inactivity sleep checker
    s_last_input_tick = xTaskGetTickCount();
    sleep_check_timer = lv_timer_create(sleep_check_cb, 250, NULL);

    // (Input scanning handled by switchboard module; we just consume events.)
    const wiseman_settings_t *ws_cur = wiseman_get();
    if (ws_cur) {
    uint8_t b = ws_cur->display_brightness < 5 ? 5 : ws_cur->display_brightness;
    backlight_set_brightness(b);
        lv_subject_set_int(&targetTemp, ws_cur->setpoint1_c);
        lv_subject_set_int(&default_temp, ws_cur->setpoint1_c);
    lv_subject_set_int(&brightness, (int)(ws_cur->display_brightness < 5 ? 5 : ws_cur->display_brightness));
        lv_subject_set_int(&sleepTimer, ws_cur->sleep_timeout_s);
        lv_subject_copy_string(&soundEnable, ws_cur->sound_enabled ? "ON" : "OFF");
        if (ws_cur->heater1_enabled && ws_cur->heater2_enabled) {
            lv_subject_copy_string(&activeCh, "CH1/2");
        } else if (ws_cur->heater1_enabled) {
            lv_subject_copy_string(&activeCh, "CH1");
        } else if (ws_cur->heater2_enabled) {
            lv_subject_copy_string(&activeCh, "CH2");
        } else {
            // If none enabled, default to CH1/2 in UI
            lv_subject_copy_string(&activeCh, "CH1/2");
        }
    }
    // State used in button handler
    uint8_t current_page = PAGE_MAIN;

    // ========= Main UI task loop (sole owner of LVGL calls) =========
    // start with home page
    load_page(PAGE_MAIN);

    ap33772s_caps_t caps = g_initial_pd_caps;
    lv_subject_set_int(&fiveV_available,    caps.fiveV    ? 1 : 0);
    lv_subject_set_int(&nineV_available,    caps.nineV    ? 1 : 0);
    lv_subject_set_int(&fifteenV_available, caps.fifteenV ? 1 : 0);
    lv_subject_set_int(&twentyV_available,  caps.twentyV  ? 1 : 0);
    int current_active = lv_subject_get_int(&activePDO);
    
    if (!(caps.fiveV || caps.nineV || caps.fifteenV || caps.twentyV)) {
        if (current_active != 0) lv_subject_set_int(&activePDO, 0);
    } else if (current_active == 0) {
        if (caps.fiveV)       lv_subject_set_int(&activePDO, 5);
        else if (caps.nineV)  lv_subject_set_int(&activePDO, 9);
        else if (caps.fifteenV) lv_subject_set_int(&activePDO, 15);
        else if (caps.twentyV) lv_subject_set_int(&activePDO, 20);
    }
    char buf[10];
    if (caps.fiveV)   { snprintf(buf, sizeof(buf), "%.2fA", caps.cur5);   lv_subject_copy_string(&fiveV,    buf);} else lv_subject_copy_string(&fiveV,    "--");
    if (caps.nineV)   { snprintf(buf, sizeof(buf), "%.2fA", caps.cur9);   lv_subject_copy_string(&nineV,    buf);} else lv_subject_copy_string(&nineV,    "--");
    if (caps.fifteenV){ snprintf(buf, sizeof(buf), "%.2fA", caps.cur15);  lv_subject_copy_string(&fifteenV, buf);} else lv_subject_copy_string(&fifteenV, "--");
    if (caps.twentyV) { snprintf(buf, sizeof(buf), "%.2fA", caps.cur20);  lv_subject_copy_string(&twentyV,  buf);} else lv_subject_copy_string(&twentyV,  "--");
    ESP_LOGI("director.pd", "PD caps applied (startup snapshot)");

    // Director is now ready to receive first sample (overwrite queue model)

    uint32_t loop_counter = 0;
    // (no-op)
    while (1) {
        // Drain button events here (replaces vConsoleTask)
        event_msg_t msg;
        while (xQueueReceive(g_button_queue, &msg, 0) == pdTRUE) {
            // Remap button ID based on display orientation
            uint8_t original_btn_id = msg.btn_id;
            msg.btn_id = remap_button_for_orientation(msg.btn_id);
            
            ESP_LOGD("director.btn", "btn id=%d->%d event=%d page=%u flipped=%d", 
                     original_btn_id, msg.btn_id, msg.event, current_page, s_display_flipped);
            
            // Update inactivity timer and handle wake on any button while sleeping
            s_last_input_tick = xTaskGetTickCount();
            if (s_display_sleeping) {
                ESP_LOGD("director.sleep", "Wake on button press (id=%d)", msg.btn_id);
                display_apply_user_brightness();
                s_display_sleeping = false;
                // Ignore this event so the first press only wakes the display
                continue;
            }
            if(msg.btn_id == BUTTON_LEFT_BOTTOM) { // "LEFT_BOTTOM"
                if (msg.event == BUTTON_EVENT_SHORT || msg.event == BUTTON_EVENT_REPEAT) {
                    uint8_t prev = current_page;
                    uint8_t next = (current_page + 1) % PAGE_COUNT;
                    if (next != current_page) {
                        unload_page(current_page);
                        current_page = next;
                        ESP_LOGI("director.page", "Page change %u -> %u", prev, current_page);
                        load_page(current_page);
                        // Log stack watermark after load
                        UBaseType_t hw = uxTaskGetStackHighWaterMark(NULL);
                        ESP_LOGD("director.stack", "after load page=%u high-water=%u words", current_page, (unsigned)hw);
                    }
                }
            }else{
                // Other buttons handled in page-specific functions
                switch(current_page) {
                    case PAGE_MAIN:     page_main(msg); break;
                    case PAGE_POWER:    page_power(msg); break;
                    case PAGE_SETTINGS: page_settings(msg); break;
                    case PAGE_INFO:     page_info(msg); break;
                    default: break;
                }
            }
        }
        
        // Consume at most one fireman sample per loop (prevents lengthy drains -> WDT risk)
        if (g_jumbo_queue) {
            fireman_sample_t latest;
            if (xQueueReceive(g_jumbo_queue, &latest, 0) == pdTRUE) {
                bool pd_fail = isnan(latest.ch1) || isnan(latest.ch2);
                if (pd_fail) {
                    lv_subject_set_int(&ch1_temp_big, 0);
                    lv_subject_set_int(&ch1_temp_small, 0);
                    lv_subject_set_int(&ch2_temp_big, 0);
                    lv_subject_set_int(&ch2_temp_small, 0);
                } else {
                    float t1 = latest.ch1; if (t1 < 0) t1 = 0;
                    int t1_whole = (int)t1;
                    int t1_dec = (int)((t1 - (float)t1_whole) * 10.0f + 0.0001f);
                    if (t1_dec < 0) t1_dec = 0; else if (t1_dec > 9) t1_dec = 9;
                    lv_subject_set_int(&ch1_temp_big, t1_whole);
                    lv_subject_set_int(&ch1_temp_small, t1_dec);

                    float t2 = latest.ch2; if (t2 < 0) t2 = 0;
                    int t2_whole = (int)t2;
                    int t2_dec = (int)((t2 - (float)t2_whole) * 10.0f + 0.0001f);
                    if (t2_dec < 0) t2_dec = 0; else if (t2_dec > 9) t2_dec = 9;
                    lv_subject_set_int(&ch2_temp_big, t2_whole);
                    lv_subject_set_int(&ch2_temp_small, t2_dec);
                }
                // No semaphore give needed
            }
        }

        lv_timer_handler();
        
        // Check tilt pin and update display orientation if needed
        tilt_check_and_update();
        
        // Update runtime display approximately once per loop (10ms delay below) but only when minute count changes.
        static uint32_t s_last_runtime_min = 0xFFFFFFFFu; // force first update
        uint32_t cur_min = wiseman_get_op_time_minutes();
        if (cur_min != s_last_runtime_min) {
            s_last_runtime_min = cur_min;
            // UI expects hours (integer). Convert minutes -> hours (truncate)
            uint32_t hours = cur_min / 60u;
            lv_subject_set_int(&runTime, (int)hours);
        }
        // Periodic stack watermark debug (every ~200 iterations)
        if ((loop_counter++ & 0xFF) == 0) {
            UBaseType_t hw = uxTaskGetStackHighWaterMark(NULL);
            ESP_LOGD("director.stack", "high-water words=%u", (unsigned)hw);
        }
        // Slightly longer delay to ensure IDLE gets time (watchdog feed)
        vTaskDelay(pdMS_TO_TICKS(10));
    }
    vTaskDelete(NULL);
}

bool director_start(QueueHandle_t button_event_queue, QueueHandle_t sample_queue, const ap33772s_caps_t *initial_pd_caps) {
    if (!button_event_queue) return false;
    director_args_full_t *args = pvPortMalloc(sizeof(director_args_full_t));
    if (!args) return false;
    args->button_q = button_event_queue;
    args->sample_q = sample_queue;
    if (initial_pd_caps) args->pd_caps = *initial_pd_caps; else memset(&args->pd_caps, 0, sizeof(args->pd_caps));
    BaseType_t ok = xTaskCreate(director_task, "director", 12288, args, 6, NULL);
    return ok == pdPASS;
}

void page_main(event_msg_t msg){
    if (msg.event == BUTTON_EVENT_SHORT) {
        switch (msg.btn_id) {
            case BUTTON_RIGHT_BOTTOM: { // "RIGHT_BOTTOM" (START/STOP)
                opStat = !opStat;
                if (opStat) {
                    lv_subject_copy_string(&command, "STOP");
                    lv_timer_resume(ui_clock_timer);
                    // START pressed: configure heaters
                    int target = lv_subject_get_int(&targetTemp);
                    if (target < 0) target = 0; else if (target > 60) target = 60;
                    // Apply the same target to both internal PID controllers for now
                    fireman_set_setpoints(target, target);
                    // Determine which channels to enable based on activeCh selection
                    const char* chsel = lv_subject_get_string(&activeCh);
                    bool en1 = false, en2 = false;
                    if (chsel) {
                        if (strcmp(chsel, "CH1") == 0) { en1 = true; en2 = false; }
                        else if (strcmp(chsel, "CH2") == 0) { en1 = false; en2 = true; }
                        else { en1 = true; en2 = true; } // "CH1/2" or fallback
                    } else { en1 = true; en2 = true; }
                    fireman_set_heater1_enabled(en1);
                    fireman_set_heater2_enabled(en2);
                    // Request higher PD voltage (20V preferred, else 15V) if available snapshot indicates support
                    ap33772s_caps_t caps_snapshot = g_initial_pd_caps; // startup snapshot
                    uint8_t desired = 0;
                    if (caps_snapshot.twentyV) desired = 20; else if (caps_snapshot.fifteenV) desired = 15; else desired = 0;
                    if (desired) {
                        bool ok = fireman_request_pd_voltage(desired);
                        // If 20V failed and we tried it first, optionally fall back to 15V if available
                        if (!ok && desired == 20 && g_initial_pd_caps.fifteenV) {
                            ok = fireman_request_pd_voltage(15);
                            if (ok) desired = 15; // reflect fallback voltage
                        }
                        ESP_LOGI("director.pd", "START PD request -> target=%uV result=%d", (unsigned)desired, (int)ok);
                        if (ok) lv_subject_set_int(&activePDO, desired);
                    } else {
                        ESP_LOGI("director.pd", "START no higher PD voltage available (stay at 5V)");
                    }
                    ESP_LOGI("director.heaters", "Heaters START target=%dC ch1=%d ch2=%d", target, en1, en2);
                } else {
                    lv_subject_copy_string(&command, "START");
                    timer_ss = timer_mm = timer_hh = 0;
                    lv_subject_copy_string(&opTime, "00:00");
                    lv_timer_pause(ui_clock_timer);
                    // STOP pressed: disable both heaters (setpoints retained for next start)
                    fireman_set_heater1_enabled(false);
                    fireman_set_heater2_enabled(false);
                    // Revert PD voltage to 5V (ignore failure)
                    bool ok = fireman_request_pd_voltage(5);
                    ESP_LOGI("director.pd", "STOP PD request 5V result=%d", (int)ok);
                    if (ok) lv_subject_set_int(&activePDO, 5);
                    ESP_LOGI("director.heaters", "Heaters STOP (disabled all)");
                }
            } break;

            case BUTTON_RIGHT_TOP: { // "RIGHT_TOP"
                int t = lv_subject_get_int(&targetTemp) + 1;
                if (t < 61) {
                    lv_subject_set_int(&targetTemp, t);
                    // Live update while running
                    if (opStat) {
                        int clamped = t; if (clamped < 0) clamped = 0; else if (clamped > 60) clamped = 60;
                        fireman_set_setpoints(clamped, clamped);
                    }
                }
            } break;

            case BUTTON_RIGHT_CENTER: { // "RIGHT_CENTER"
                int t = lv_subject_get_int(&targetTemp) - 1;
                if (t > -1) {
                    lv_subject_set_int(&targetTemp, t);
                    // Live update while running
                    if (opStat) {
                        int clamped = t; if (clamped < 0) clamped = 0; else if (clamped > 60) clamped = 60;
                        fireman_set_setpoints(clamped, clamped);
                    }
                }
            } break;
        }
    } else if (msg.event == BUTTON_EVENT_REPEAT) {
        switch (msg.btn_id) {
            case BUTTON_RIGHT_TOP: { // "RIGHT_TOP" (increment hold)
                int t = lv_subject_get_int(&targetTemp) + 1;
                if (t < 61) {
                    lv_subject_set_int(&targetTemp, t);
                    if (opStat) {
                        int clamped = t; if (clamped < 0) clamped = 0; else if (clamped > 60) clamped = 60;
                        fireman_set_setpoints(clamped, clamped);
                    }
                }
            } break;

            case BUTTON_RIGHT_CENTER: { // "RIGHT_CENTER" (decrement hold)
                int t = lv_subject_get_int(&targetTemp) - 1;
                if (t > -1) {
                    lv_subject_set_int(&targetTemp, t);
                    if (opStat) {
                        int clamped = t; if (clamped < 0) clamped = 0; else if (clamped > 60) clamped = 60;
                        fireman_set_setpoints(clamped, clamped);
                    }
                }
            } break;
        }
    }
}

