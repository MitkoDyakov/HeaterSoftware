static lv_obj_t * find_obj_by_name(lv_obj_t * root, const char * name) {
    if (!root || !name) return NULL;
    const char * n = lv_obj_get_name(root);
    if (n && strcmp(n, name) == 0) return root;
    uint32_t child_cnt = lv_obj_get_child_cnt(root);
    for (uint32_t i = 0; i < child_cnt; ++i) {
        lv_obj_t * child = lv_obj_get_child(root, i);
        lv_obj_t * found = find_obj_by_name(child, name);
        if (found) return found;
    }
    return NULL;
}

static void load_page(uint8_t page_id) {
    if (!s_page_container) return; // not ready yet
    lv_obj_clean(s_page_container);
    lv_subject_set_int(&pageSelect, (int)page_id);
    switch(page_id) {
        case PAGE_MAIN: {
            lv_obj_t * row_4 = row_create(s_page_container);
            lv_obj_set_width(row_4, 141);
            lv_obj_set_height(row_4, 83);

            lv_obj_t * target_tmp_0 = target_tmp_create(row_4, &targetTemp);
            lv_obj_set_style_pad_all(target_tmp_0, 0, 0);

            lv_obj_t * row_5 = row_create(s_page_container);
            lv_obj_set_width(row_5, 141);
            lv_obj_set_height(row_5, 39);
            lv_obj_set_style_margin_top(row_5, 4, 0);

            lv_obj_t * control_0 = control_create(row_5, &command, &opTime);
            lv_obj_set_style_pad_all(control_0, 0, 0);
            
            // lv_subject_copy_string(&ch1_active, "ON");
            // lv_subject_copy_string(&ch2_active, "ON");
        } break;
        case PAGE_SETTINGS: {
            (void)settings_create(s_page_container);
            // Initialize selection and edit state
            s_settings_edit_mode = false;
            s_settings_blink_on = false;
            s_settings_selected_idx = 0;
            lv_subject_set_int(&settingsSelect, s_settings_selected_idx); // highlight first setting
        } break;
        case PAGE_POWER: {
            (void)power_create(s_page_container);
        } break;
        case PAGE_INFO: {
            (void)info_create(s_page_container);
        } break;
        default: break;
    }
}

static void unload_page(uint8_t page_id) {
    switch(page_id) {
        case PAGE_MAIN: {
            //clean up page 1 resources if any
        } break;
        case PAGE_POWER: {
            //clean up page 2 resources if any
        } break;
        case PAGE_SETTINGS: {
            // Persist settings once on leaving the Settings page
            // Also exit edit mode and normalize selector
            s_settings_edit_mode = false;
            s_settings_blink_on = false;
            if (lv_subject_get_int(&settingsSelect) != s_settings_selected_idx) {
                lv_subject_set_int(&settingsSelect, s_settings_selected_idx);
            }
            const char* ch = lv_subject_get_string(&activeCh);
            bool ch1 = false, ch2 = false;
            if (ch) {
                if (strcmp(ch, "CH1") == 0) { ch1 = true; ch2 = false; }
                else if (strcmp(ch, "CH2") == 0) { ch1 = false; ch2 = true; }
                else { ch1 = true; ch2 = true; } // "CH1/2"
            }
            int t = lv_subject_get_int(&default_temp);
            if (t < 0) t = 0; else if (t > 60) t = 60;
            wiseman_set_setpoint1((int16_t)t);

            int b = lv_subject_get_int(&brightness);
            if (b < 0) b = 0; else if (b > 100) b = 100;
            wiseman_set_display_brightness((uint8_t)b);

            int st = lv_subject_get_int(&sleepTimer);
            if (st < 0) st = 0; else if (st > 60) st = 60;
            wiseman_set_sleep_timeout_seconds((uint16_t)st);

            const char* snd = lv_subject_get_string(&soundEnable);
            wiseman_set_sound_enabled(snd && strcmp(snd, "ON") == 0);
            wiseman_set_heaters_enabled(ch1, ch2);

            wiseman_request_flush(); // non-blocking: persistence task will commit shortly
        } break;
        case PAGE_INFO: {
            //clean up page 4 resources if any
        } break;
        default: break;
    }
}   

